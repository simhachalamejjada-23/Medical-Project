from pathlib import Path

import joblib
import matplotlib.pyplot as plt
import pandas as pd
import streamlit as st


# ------------------------------------------------------------
# 1. PAGE CONFIGURATION
# ------------------------------------------------------------

BASE_DIR = Path(__file__).resolve().parent
DATASET_PATH = BASE_DIR / "archive" / "data.csv"
MODEL_DIR = BASE_DIR / "models"
RESULTS_DIR = BASE_DIR / "results"

st.set_page_config(
    page_title="Breast Cancer Classification",
    page_icon="🩺",
    layout="wide"
)

st.title("Breast Cancer Classification")
st.caption("Machine learning model comparison, prediction and explainability")


# ------------------------------------------------------------
# 2. MODEL FILES
# ------------------------------------------------------------

MODEL_FILES = {
    "Logistic Regression": "logistic_regression_model.pkl",
    "SVM": "svm_model.pkl",
    "KNN": "knn_model.pkl",
    "Decision Tree": "decision_tree_model.pkl",
    "Random Forest": "random_forest_model.pkl",
    "Gradient Boosting": "gradient_boosting_model.pkl",
}


# ------------------------------------------------------------
# 3. LOAD DATA AND MODELS
# ------------------------------------------------------------

@st.cache_data
def load_dataset(path_string):
    data = pd.read_csv(path_string)

    data = data.drop(
        columns=["id", "Unnamed: 32"],
        errors="ignore"
    ).drop_duplicates()

    data["diagnosis"] = data["diagnosis"].map({
        "B": 0,
        "M": 1
    })

    data = data.dropna(subset=["diagnosis"])

    X = data.drop(columns=["diagnosis"]).apply(
        pd.to_numeric,
        errors="coerce"
    )

    valid_rows = X.notna().all(axis=1)
    X = X.loc[valid_rows].reset_index(drop=True)

    return X


@st.cache_resource
def load_model(path_string):
    return joblib.load(path_string)


if not DATASET_PATH.exists():
    st.error(f"Dataset not found: {DATASET_PATH}")
    st.stop()

X_reference = load_dataset(str(DATASET_PATH))
feature_names = list(X_reference.columns)

available_models = {
    name: MODEL_DIR / filename
    for name, filename in MODEL_FILES.items()
    if (MODEL_DIR / filename).exists()
}

if not available_models:
    st.error(
        "No trained model files were found. "
        "Run `py breast_cancer.py` first to create the models folder."
    )
    st.stop()


# ------------------------------------------------------------
# 4. SIDEBAR
# ------------------------------------------------------------

st.sidebar.header("Prediction Settings")

selected_model_name = st.sidebar.selectbox(
    "Choose a machine learning model",
    list(available_models.keys())
)

st.sidebar.info(
    "The prediction is generated by the selected model using "
    "the 30 numeric features from the Wisconsin Breast Cancer dataset."
)


# ------------------------------------------------------------
# 5. TABS
# ------------------------------------------------------------

prediction_tab, comparison_tab, explainability_tab = st.tabs([
    "Prediction",
    "Model Comparison",
    "Explainable AI"
])


# ------------------------------------------------------------
# 6. PREDICTION TAB
# ------------------------------------------------------------

with prediction_tab:
    st.subheader("Enter Tumor Measurements")

    st.write(
        "The inputs are initialized to the median values in the dataset. "
        "Change them to explore how the selected model responds."
    )

    with st.form("prediction_form"):
        st.markdown("#### Tumor feature values")

        columns = st.columns(3)
        input_values = {}

        for index, feature in enumerate(feature_names):
            col = columns[index % 3]

            minimum = float(X_reference[feature].min())
            maximum = float(X_reference[feature].max())
            median = float(X_reference[feature].median())

            if minimum == maximum:
                minimum = minimum - 0.000001
                maximum = maximum + 0.000001

            step = max((maximum - minimum) / 1000, 0.000001)

            with col:
                input_values[feature] = st.number_input(
                    feature,
                    min_value=minimum,
                    max_value=maximum,
                    value=min(max(median, minimum), maximum),
                    step=step,
                    format="%.6f",
                    help=f"Dataset range: {minimum:.4f} to {maximum:.4f}"
                )

        submitted = st.form_submit_button(
            "Predict Diagnosis",
            type="primary",
            width="stretch",
        )

    if submitted:
        model_path = available_models[selected_model_name]

        try:
            selected_model = load_model(str(model_path))

            input_df = pd.DataFrame(
                [input_values],
                columns=feature_names
            )

            prediction = int(selected_model.predict(input_df)[0])

            st.markdown("---")
            st.subheader("Prediction Result")

            if prediction == 1:
                st.error("Model prediction: Malignant")
            else:
                st.success("Model prediction: Benign")

            if hasattr(selected_model, "predict_proba"):
                probabilities = selected_model.predict_proba(input_df)[0]

                benign_probability = float(probabilities[0])
                malignant_probability = float(probabilities[1])

                metric1, metric2 = st.columns(2)

                metric1.metric(
                    "Benign probability",
                    f"{benign_probability * 100:.2f}%"
                )

                metric2.metric(
                    "Malignant probability",
                    f"{malignant_probability * 100:.2f}%"
                )

                st.write("Prediction probability")
                st.progress(malignant_probability)

            st.caption(
                f"Model used: {selected_model_name}"
            )

        except Exception as error:
            st.error(f"Prediction could not be completed: {error}")


# ------------------------------------------------------------
# 7. MODEL COMPARISON TAB
# ------------------------------------------------------------

with comparison_tab:
    st.subheader("Model Performance Comparison")

    comparison_path = RESULTS_DIR / "model_comparison_results.csv"
    auc_path = RESULTS_DIR / "auc_comparison.csv"
    roc_image = RESULTS_DIR / "roc_curve_comparison.png"
    accuracy_image = RESULTS_DIR / "model_accuracy_comparison.png"
    confusion_image = RESULTS_DIR / "confusion_matrix.png"

    if comparison_path.exists():
        comparison_df = pd.read_csv(comparison_path)
        st.markdown("#### Classification metrics")
        st.dataframe(comparison_df, width="stretch")

    if auc_path.exists():
        auc_df = pd.read_csv(auc_path)
        st.markdown("#### ROC-AUC comparison")
        st.dataframe(auc_df, width="stretch")

    col1, col2 = st.columns(2)

    with col1:
        if accuracy_image.exists():
            st.markdown("#### Test accuracy")
            st.image(str(accuracy_image), width="stretch")

    with col2:
        if confusion_image.exists():
            st.markdown("#### Best model confusion matrix")
            st.image(str(confusion_image), width="stretch")

    if roc_image.exists():
        st.markdown("#### ROC curve comparison")
        st.image(str(roc_image), width="stretch")

    if not comparison_path.exists() and not auc_path.exists():
        st.warning(
            "Comparison files are not available. "
            "Run the training and ROC analysis scripts first."
        )


# ------------------------------------------------------------
# 8. EXPLAINABLE AI TAB
# ------------------------------------------------------------

with explainability_tab:
    st.subheader("Feature Importance and SHAP Explanations")

    feature_importance_path = RESULTS_DIR / "feature_importance.png"
    shap_summary_path = RESULTS_DIR / "shap_summary.png"
    shap_bar_path = RESULTS_DIR / "shap_feature_importance.png"
    feature_csv_path = RESULTS_DIR / "feature_importance.csv"
    shap_csv_path = RESULTS_DIR / "shap_feature_importance.csv"

    if feature_importance_path.exists():
        st.markdown("#### Random Forest feature importance")
        st.image(
            str(feature_importance_path),
            width="stretch"
        )

    if feature_csv_path.exists():
        st.markdown("#### Feature importance values")
        feature_df = pd.read_csv(feature_csv_path)
        st.dataframe(feature_df, width="stretch")

    if shap_summary_path.exists():
        st.markdown("#### SHAP summary plot")
        st.image(
            str(shap_summary_path),
            width="stretch"
        )

    if shap_bar_path.exists():
        st.markdown("#### SHAP feature importance plot")
        st.image(
            str(shap_bar_path),
            width="stretch"
        )

    if shap_csv_path.exists():
        st.markdown("#### SHAP numerical results")
        shap_df = pd.read_csv(shap_csv_path)
        st.dataframe(shap_df, width="stretch")

    if not any([
        feature_importance_path.exists(),
        shap_summary_path.exists(),
        shap_bar_path.exists()
    ]):
        st.warning(
            "Explainability plots are not available. "
            "Run feature_importance.py and shap_analysis.py first."
        )


